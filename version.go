package main

import "strings"

// version はビルド時に -ldflags "-X main.version=<タグ>" で注入する
// バージョン文字列。未注入時は "dev"(IMPL-21、NFR-11)。
var version = "dev"

// versionLine は --version が標準出力へ表示する 1 行を返す
// (design.md「errors / version」: `json2ndjson <version>`)。
//
// --version / --help の引数としての受け付けと終了コード 0 での終了は
// タスク 4.1(引数解析)の責務。
func versionLine() string {
	return "json2ndjson " + version
}

// usageText は --help が表示する使い方の全文を返す(要件 7.6)。
//
// 本ツールは自身のログファイルを持たず(要件 11.2 / NFR-10)、記録は呼び出し元が取得する
// 標準出力・標準エラー出力・終了コードに集約される。したがってこのヘルプが運用者にとって
// 唯一の文書であり、全引数・終了コード体系・注意事項をここで説明しきる必要がある。
//
// 重複排除のメモリ特性(要件 9.4 / NFR-05)は transform.go の dedupeMemoryNote が
// 唯一の出典であり、ここへ埋め込むことで文言の二重管理を避ける。
//
// 表示(stdout への書き出し)と終了コード 0 での終了は main の責務。
func usageText() string {
	var b strings.Builder
	b.WriteString(versionLine())
	b.WriteString(`
JSON ファイルを NDJSON(1 行 1 JSON 値)へ変換します。

使い方:
  json2ndjson --in <入力ファイル> --out <出力ファイル> [オプション]

入出力:
  --in <パス>
        入力 JSON ファイル(UTF-8、BOM の有無は問わない)。必須。
        複数回指定でき、ファイル名(ベース名、同名時はフルパス)の昇順に処理します。
  --out <パス>
        出力 NDJSON ファイルの絶対パス。必須。空白や日本語を含むパスも扱えます。
  --path <JSON Pointer>
        変換対象の位置(RFC 6901)。省略時はルート。
        位置が配列なら各要素を 1 レコード、オブジェクトならそれ自体を 1 レコードとして出力します。
        例: --path /data/items("" はルート、"/" は空文字列キーで別物です)

書き込みモード:
  --append
        既存の出力ファイルの末尾へ追記します。ファイルがなければ新規作成します。
        末尾が改行で終わっていない場合は改行を補ってから追記します。
  --overwrite
        既存の出力ファイルを上書きします(--append との同時指定はできません)。
        --append も --overwrite もない状態で出力ファイルが既に存在する場合は終了コード 4 で停止します。

出力形式:
  --newline lf|crlf
        行の改行コード。既定は lf。
  --no-trailing-newline
        最終行に改行を付けません。既定では最終行にも改行を付けます。

結果行(標準出力の 1 行):
  --cursor-key <JSON Pointer>
        最後に出力したレコードの指定位置の値を last_id=<値> として結果行に含めます。
        出力件数が 0 件のときは last_id を出力しません。
        指定位置が最後のレコードに存在しない場合、値が非スカラーまたは ASCII 範囲外の場合は終了コード 5 です。

整形(いずれも既定では無効):
  --dedupe-key <JSON Pointer>
        指定位置の値が同一のレコードを同一実行内で 1 回だけ出力します(先に現れたものを残す)。
        --append の既存ファイルの内容は対象外です。
        指定位置が存在しないレコードは重複排除の対象外として常に出力します。
  --key-hyphen-to-underscore
        すべての階層のキー名に含まれる - を _ に置換します(値は変更しません)。
  --add-field <キー=値>
        各レコードのトップレベルに固定値の文字列フィールドを追加します。複数回指定できます。
        最初の = で分割するため値に = を含められます(a=b=c はキー a・値 b=c)。
        キーは空にできず、同じキーを 2 回指定することもできません。
        レコードの既存キーと衝突した場合は終了コード 1 です。
  --max-record-bytes <正の整数>
        1 レコード(整形後)の上限バイト数。超過は終了コード 5 です。
  --skip-oversize
        上限超過レコードを標準エラー出力に警告して読み飛ばし、処理を継続します。
        単独では指定できず、--max-record-bytes と併せて指定します。

その他:
  --version
        バージョンを表示して終了します。
  --help
        この使い方を表示して終了します。

終了コード:
  0 正常終了 / 1 引数不正 / 2 入力ファイル不可 / 3 JSON 構文エラー
  4 出力書き込みエラー(権限・ディスク・排他・既存ファイル) / 5 位置不正 / 9 予期しない内部エラー

注意:
  - 設定はすべて引数で指定します。環境変数や設定ファイルによる暗黙の設定はありません。
  - 標準出力は結果行(records=<件数> files=<件数> [last_id=<値>])だけに使います。
    エラーメッセージは標準エラー出力へ出ます。
  - 入力ファイルは読み取り専用で開き、変更も削除もしません。
  - ` + dedupeMemoryNote + `
`)
	return b.String()
}
